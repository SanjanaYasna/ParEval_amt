def extract_error_lines(text: str, phase: str) -> List[str]:
    """
    Extract actual error lines.

    Build stderr:
        Trust compiler/linker error markers. Do not treat arbitrary uses of
        words such as "exception" as errors, since HPX headers and compiler
        context frequently contain them.

    Runtime stderr:
        Also recognize exception/crash diagnostics that do not use "error:".
    """
    if not text:
        return []

    errors = []

    for line in text.splitlines():
        # Skip compiler warnings/notes/info.
        if re.search(
            r":\s*(warning|note|info):",
            line,
            re.IGNORECASE,
        ):
            continue

        # --------------------------------------------------------------
        # BUILD + RUNTIME: explicit error diagnostics
        # --------------------------------------------------------------

        if re.search(r":\s*(fatal\s+)?error:", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        # Linker diagnostics.
        if re.search(r"undefined reference to", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"ld returned.*exit status", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"cannot find.*lib", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        # For compilation, stop here.
        #
        # This prevents lines such as:
        #
        #   In file included from .../exception_fwd.hpp
        #   hpx::exception
        #   void throw_exception(...)
        #
        # from being mistaken for compiler errors.
        if phase == "build":
            continue

        # --------------------------------------------------------------
        # RUNTIME ONLY
        # --------------------------------------------------------------

        if re.search(r"Segmentation fault", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"signal.*SIGSEGV", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"Aborted", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"out of memory", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(
            r"terminate called after throwing",
            line,
            re.IGNORECASE,
        ):
            errors.append(line.strip())
            continue

        # Broad exception matching is safe here because we already know
        # this is runtime stderr, not compiler include/template context.
        if re.search(r"exception", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"runtime error", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

        if re.search(r"assert.*failed", line, re.IGNORECASE):
            errors.append(line.strip())
            continue

    return errors


def categorize_error(error_line: str, phase: str) -> str:
    """Categorize a single error line based on configured patterns."""
    for category, config in ERROR_CATEGORIES.items():
        for pattern in config["patterns"]:
            if re.search(pattern, error_line, re.IGNORECASE):
                return category
    if phase == "runtime":
        return "Other_Runtime_Error" #record unexpected runtime to add tolist
    print(error_line)
    return "Other_Compilation"


