def main() -> None:
    if len(sys.argv) != 3:
        print(
            f"Usage: {sys.argv[0]} "
            "<input_directory> <output_directory>"
        )
        print()
        print("Example:")
        print(
            f"  python {sys.argv[0]} "
            "/work/pi_mrobson_smith_edu/scratch/"
            "generation_hpx/la/driver/tcmalloc "
            "./errors"
        )
        print()
        print(
            "The input directory should contain "
            "<model>_combined.json files."
        )
        print(
            "Currently analyzed models: "
            + ", ".join(
                sorted(SUPPORTED_MODELS)
            )
        )
        sys.exit(1)

    input_dir = sys.argv[1]
    output_dir = sys.argv[2]

    # ------------------------------------------------------------------
    # Validate input directory
    # ------------------------------------------------------------------

    if not os.path.isdir(input_dir):
        print(
            "ERROR: Input directory does not exist: "
            f"{input_dir}"
        )
        sys.exit(1)

    # ------------------------------------------------------------------
    # Create output directory
    # ------------------------------------------------------------------

    os.makedirs(
        output_dir,
        exist_ok=True,
    )

    # ------------------------------------------------------------------
    # Discover supported model JSON files
    # ------------------------------------------------------------------

    model_files = discover_model_files(
        input_dir
    )

    if not model_files:
        print(
            "ERROR: No supported *_combined.json "
            "files found."
        )
        print()
        print(
            "Currently supported models: "
            + ", ".join(
                sorted(SUPPORTED_MODELS)
            )
        )
        sys.exit(1)

    print("=" * 80)
    print("HPX ERROR EXTRACTION")
    print("=" * 80)
    print()
    print(
        f"Input directory:  {input_dir}"
    )
    print(
        f"Output directory: {output_dir}"
    )
    print()

    print("Relevant model JSON files found:")

    for model_name in sorted(model_files):
        print(
            f"  {model_name:10} -> "
            f"{os.path.basename(model_files[model_name])}"
        )

    # ------------------------------------------------------------------
    # Process each model independently
    # ------------------------------------------------------------------

    total_error_rows = 0
    total_outputs_processed = 0
    models_processed = 0

    for model_name in sorted(model_files):
        results_file = model_files[
            model_name
        ]

        print()
        print("=" * 80)
        print(
            f"PROCESSING MODEL: {model_name}"
        )
        print("=" * 80)
        print(
            f"Source JSON: {results_file}"
        )

        problems = parse_results_file(
            results_file
        )

        if not problems:
            print(
                "WARNING: No problem entries "
                f"found for {model_name}."
            )

            # Still create an empty CSV so that the
            # existence of the file indicates the model
            # was considered.
            output_csv = os.path.join(
                output_dir,
                f"{model_name}_errors.csv",
            )

            write_error_csv(
                analyses=[],
                output_file=output_csv,
                model_name=model_name,
            )

            print(
                f"Created empty CSV: {output_csv}"
            )
            continue

        total_outputs = sum(
            len(problem.get("outputs", []))
            for problem in problems
            if (
                isinstance(problem, dict)
                and isinstance(
                    problem.get("outputs", []),
                    list,
                )
            )
        )

        print(
            f"Problem entries:    {len(problems)}"
        )
        print(
            f"Generated outputs:  {total_outputs}"
        )

        analyses = analyze_results(
            problems
        )

        # --------------------------------------------------------------
        # Construct output filename from model name.
        #
        # glm_combined.json
        #       ->
        # glm_errors.csv
        # --------------------------------------------------------------

        problem_types = get_problem_types(problems)

        if "dense_la" in problem_types or "sparse_la" in problem_types:

            error_count = 0

            for la_type in ["dense_la", "sparse_la"]:

                if la_type not in problem_types:
                    continue

                la_output_dir = os.path.join(
                    output_dir,
                    la_type,
                )

                os.makedirs(
                    la_output_dir,
                    exist_ok=True,
                )

                output_csv = os.path.join(
                    la_output_dir,
                    f"{model_name}_errors.csv",
                )

                count = write_error_csv(
                    analyses=analyses,
                    output_file=output_csv,
                    model_name=model_name,
                    problem_type_filter=la_type,
                )

                error_count += count

                print(
                    f"Error CSV saved: {output_csv} "
                    f"({count} rows)"
                )

        else:

            output_csv = os.path.join(
                output_dir,
                f"{model_name}_errors.csv",
            )

            error_count = write_error_csv(
                analyses=analyses,
                output_file=output_csv,
                model_name=model_name,
            )

            print(
                f"Error CSV saved: {output_csv} "
                f"({error_count} rows)"
            )

            print_model_summary(
                model_name=model_name,
                analyses=analyses,
            )

            print()
            print(
                f"Error CSV saved: {output_csv}"
            )

            total_error_rows += error_count
            total_outputs_processed += len(
                analyses
            )
            models_processed += 1

    # ------------------------------------------------------------------
    # Final summary
    # ------------------------------------------------------------------

    print()
    print("=" * 80)
    print("DONE")
    print("=" * 80)

    print(
        f"Models processed:          {models_processed}"
    )
    print(
        f"Generated outputs scanned: {total_outputs_processed}"
    )
    print(
        f"Total error rows written:  {total_error_rows}"
    )
    print(
        f"Output directory:          {output_dir}"
    )

    print()
    print("Generated error CSVs:")

    for model_name in sorted(model_files):
        output_csv = os.path.join(
            output_dir,
            f"{model_name}_errors.csv",
        )

        print(
            f"  {output_csv}"
        )


if __name__ == "__main__":
    main()