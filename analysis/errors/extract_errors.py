def get_first_runtime_stderr(
    output: Dict[str, Any]
) -> Optional[Dict[str, Any]]:
    """
    Return information about the first run with nonempty stderr.

    Only ONE run contributes runtime stderr for each generated output.

    For example:

        thread 1  -> stderr empty
        thread 2  -> stderr empty
        thread 4  -> Segmentation fault
        thread 8  -> Segmentation fault
        thread 16 -> Segmentation fault

    Only the thread-4 stderr is analyzed.
    """
    runs = output.get("runs")

    if not runs or not isinstance(runs, list):
        return None

    for run_index, run in enumerate(runs):
        if not isinstance(run, dict):
            continue
        #ignore if it did_run
        if run.get("did_run"):
            continue
        stderr = run.get("stderr", "")
        
        if ignore_runtime_stderr(stderr): continue 

        if isinstance(stderr, str) and stderr.strip():
            return {
                "run_index": run_index,
                "num_threads": run.get("num_threads"),
                "stderr": stderr,
                "did_run": run.get("did_run"),
                "is_valid": run.get("is_valid"),
                "runtime": run.get("runtime"),
            }

    return None


