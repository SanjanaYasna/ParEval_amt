# ANALYZE ALL PROBLEMS / OUTPUTS FOR ONE MODEL
# ============================================================================

def analyze_results(
    problems: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    Flatten:

        problem
            -> outputs[]
                -> generated output

    into one analysis record per generated output.
    """

    analyses = []

    for problem in problems:
        if not isinstance(problem, dict):
            continue

        outputs = problem.get(
            "outputs",
            [],
        )

        if not isinstance(outputs, list):
            print(
                "WARNING: Problem "
                f"{problem.get('name', 'unknown')} "
                "has an invalid outputs field."
            )
            continue

        # Zero-based numbering:
        #
        # outputs[0] -> output_number 0
        # outputs[1] -> output_number 1
        # ...
        #
        # Change to enumerate(outputs, start=1) if you
        # prefer human-oriented 1-based numbering.
        for output_number, output in enumerate(
            outputs
        ):
            if not isinstance(output, dict):
                continue

            analyses.append(
                analyze_output(
                    problem=problem,
                    output=output,
                    output_number=output_number,
                )
            )

    return analyses


