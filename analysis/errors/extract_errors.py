def get_problem_types(
    problems: List[Dict[str, Any]]
) -> set:
    """Return all problem_type values present in a model's results."""
    return {
        problem.get("problem_type")
        for problem in problems
        if (
            isinstance(problem, dict)
            and problem.get("problem_type")
        )
    }
    
def write_error_csv(
    analyses: List[Dict[str, Any]],
    output_file: str,
    model_name: str,
    problem_type_filter: Optional[str] = None,
) -> int:
    """
    Write extracted errors for one model.

    If problem_type_filter is provided, only errors belonging to that
    problem type are written.
    """
    csv_rows = []

    for analysis in analyses:
        if (
            problem_type_filter is not None
            and analysis["problem_type"] != problem_type_filter
        ):
            continue

        for original_row in analysis["build_error_rows"]:
            row = dict(original_row)
            row["model"] = model_name
            csv_rows.append(row)

        for original_row in analysis["runtime_error_rows"]:
            row = dict(original_row)
            row["model"] = model_name
            csv_rows.append(row)

    fieldnames = [
        "model",
        "problem_name",
        "problem_type",
        "language",
        "parallelism_model",
        "output_number",
        "phase",
        "source",
        "num_threads",
        "error_type",
        "error_message",
        "did_build",
        "is_source_valid",
        "did_any_run",
        "did_all_run",
        "are_any_valid",
        "are_all_valid",
    ]

    with open(
        output_file,
        "w",
        newline="",
        encoding="utf-8",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames,
        )

        writer.writeheader()
        writer.writerows(csv_rows)

    return len(csv_rows)

