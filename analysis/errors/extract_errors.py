def analyze_output(
    problem: Dict[str, Any],
    output: Dict[str, Any],
    output_number: int,
) -> Dict[str, Any]:
    """
    Analyze one generated output belonging to one HPX problem.

    The enclosing problem contains metadata such as:
        name
        problem_type
        language
        parallelism_model

    The output contains:
        generated_output
        did_build
        runs
        validation flags
        etc.
    """

    problem_name = problem.get("name", "unknown")
    problem_type = problem.get("problem_type", "unknown")
    language = problem.get("language", "unknown")
    parallelism_model = problem.get(
        "parallelism_model",
        "unknown",
    )

    build_error_counts = defaultdict(int)
    build_error_messages = defaultdict(list)
    build_error_rows = []

    runtime_error_counts = defaultdict(int)
    runtime_error_messages = defaultdict(list)
    runtime_error_rows = []

    # ------------------------------------------------------------------
    # BUILD STDERR
    # ------------------------------------------------------------------
    #
    # The example JSON does not show build_stderr, but support it in case
    # the full validation output contains it.
    #

    
    if output.get("did_build") is False:
        stderr_text = output.get("build_stderr", "")

        if isinstance(stderr_text, str) and stderr_text.strip():
            for error_line in extract_error_lines(stderr_text, phase="build"):
                category = categorize_error(
                    error_line,
                    phase="build",
                )

                build_error_counts[category] += 1

                if error_line not in build_error_messages[category]:
                    build_error_messages[category].append(error_line)

                build_error_rows.append({
                    "problem_name": problem_name,
                    "problem_type": problem_type,
                    "language": language,
                    "parallelism_model": parallelism_model,
                    "output_number": output_number,
                    "phase": "build",
                    "source": "build",
                    "num_threads": "",
                    "error_type": category,
                    "error_message": error_line,
                    "did_build": output.get("did_build"),
                    "is_source_valid": output.get("is_source_valid"),
                    "did_any_run": output.get("did_any_run"),
                    "did_all_run": output.get("did_all_run"),
                    "are_any_valid": output.get("are_any_valid"),
                    "are_all_valid": output.get("are_all_valid"),
                })

    # ------------------------------------------------------------------
    # RUNTIME STDERR
    # ------------------------------------------------------------------
    #
    # Only the first run containing stderr is analyzed.
    #

    first_runtime_error = get_first_runtime_stderr(
        output
    )

    if first_runtime_error is not None:
        stderr_text = first_runtime_error["stderr"]
        num_threads = first_runtime_error[
            "num_threads"
        ]
        run_index = first_runtime_error[
            "run_index"
        ]

        for error_line in extract_error_lines(stderr_text, phase="runtime"):
            category = categorize_error(
                    error_line, "runtime"
                )
        # #reomve validation fails (assertions usually)
        # if not is_validation_failure(stderr_text): 
        #     error_lines = extract_error_lines(
        #     stderr_text
        # )

            runtime_error_counts[category] += 1

            if error_line not in runtime_error_messages[category]:
                runtime_error_messages[category].append(error_line)

            runtime_error_rows.append({
                "problem_name": problem_name,
                "problem_type": problem_type,
                "language": language,
                "parallelism_model": parallelism_model,
                "output_number": output_number,
                "phase": "runtime",
                "source": f"run[{run_index}]",
                "num_threads": num_threads,
                "error_type": category, #always runtime anyway
                "error_message": error_line,
                "did_build": output.get("did_build"),
                "is_source_valid": output.get(
                    "is_source_valid"
                ),
                "did_any_run": output.get(
                    "did_any_run"
                ),
                "did_all_run": output.get(
                    "did_all_run"
                ),
                "are_any_valid": output.get(
                    "are_any_valid"
                ),
                "are_all_valid": output.get(
                    "are_all_valid"
                ),
            })

    total_build_errors = sum(
        build_error_counts.values()
    )

    total_runtime_errors = sum(
        runtime_error_counts.values()
    )

    return {
        "problem_name": problem_name,
        "problem_type": problem_type,
        "language": language,
        "parallelism_model": parallelism_model,
        "output_number": output_number,

        "did_build": output.get("did_build"),
        "is_source_valid": output.get(
            "is_source_valid"
        ),
        "did_any_run": output.get(
            "did_any_run"
        ),
        "did_all_run": output.get(
            "did_all_run"
        ),
        "are_any_valid": output.get(
            "are_any_valid"
        ),
        "are_all_valid": output.get(
            "are_all_valid"
        ),

        "build_error_counts": dict(
            build_error_counts
        ),
        "build_error_messages": dict(
            build_error_messages
        ),
        "build_error_rows": build_error_rows,

        "runtime_error_counts": dict(
            runtime_error_counts
        ),
        "runtime_error_messages": dict(
            runtime_error_messages
        ),
        "runtime_error_rows": runtime_error_rows,

        "first_runtime_error": first_runtime_error,

        "total_build_errors": total_build_errors,
        "total_runtime_errors": total_runtime_errors,
        "total_errors": (
            total_build_errors
            + total_runtime_errors
        ),
    }


