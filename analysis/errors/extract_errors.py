def discover_model_files(input_dir: str) -> Dict[str, str]:
    """
    Find supported <model>_combined.json files in the input directory.

    Example:
        glm_combined.json
            -> model_name = "glm"

        minimax_combined.json
            -> model_name = "minimax"

    Files for unsupported models are ignored.
    """
    model_files = {}

    suffix = "_combined.json"

    for filename in os.listdir(input_dir):
        if not filename.endswith(suffix):
            continue

        model_name = filename[:-len(suffix)]

        if model_name not in SUPPORTED_MODELS:
            continue

        filepath = os.path.join(input_dir, filename)

        if os.path.isfile(filepath):
            model_files[model_name] = filepath

    return model_files


def parse_results_file(filepath: str) -> List[Dict[str, Any]]:
    """Load one model's HPX validation results JSON file."""
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, list):
            raise ValueError(
                "Expected the top-level JSON value to be a list."
            )

        return data

    except Exception as e:
        print(f"ERROR: Could not load {filepath}: {e}")
        return []
    


